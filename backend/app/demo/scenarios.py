"""
Deterministic demo scenarios for TRACE M1 evaluation.

Implements the 6 primary evaluation scenarios:
1. valid_claim: authentic signature, approved category, verified spending.
2. tampered_amount: invoice amount altered after vendor signature.
3. forged_signature: signature generated by unauthorized attacker key.
4. unregistered_vendor: receipt from vendor not in authorized registry.
5. duplicate_report: cross-report duplicate claim on same vendor invoice.
6. out_of_purpose: claim for unapproved category (fund diversion).

Each scenario returns: actual result, rejection reason, project status, and next release outcome.
"""
import time
from typing import Any, Dict, List, Optional

from backend.app.db import Database
from backend.app.demo.vendors import (
    ATTACKER_SIGNER,
    TEST_EVIDENCE_BYTES,
    TEST_EVIDENCE_COMMITMENT,
    TEST_EVIDENCE_SALT,
    VENDOR_SOLAR_PUMP,
    VENDOR_UNREGISTERED,
    VENDOR_WELL_DRILL,
)
from backend.app.models.receipt import EIP712Domain, Receipt
from backend.app.services.escrow_sim import SimulatedEscrowService
from backend.app.services.signatures import sign_receipt


