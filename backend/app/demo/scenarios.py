def list_demo_scenarios() -> List[Dict[str, Any]]:
    """Returns catalog of all available demo scenarios."""
    return SCENARIOS_CATALOG


def run_scenario(name: str, db: Database) -> Dict[str, Any]:
    """
    Executes a named demo scenario against the database and returns structured evaluation results.
    """
    domain = EIP712Domain()
    escrow = SimulatedEscrowService(db)
    now = int(time.time())

    # Ensure Tranche 1 is released if project is currently unreleased at Tranche 0
    proj_water = db.get_project("WATER-001")
    if proj_water and proj_water["current_tranche"] == 0 and not proj_water["is_frozen"]:
        db.release_next_tranche("WATER-001")

    if name == "valid_claim":
        rec = Receipt(
            project_id="WATER-001",
            vendor_id=VENDOR_WELL_DRILL.vendor_id,
            invoice_id="INV-DEMO-001",
            invoice_total=500000,  # $5,000 USD
            currency="USD",
            category="WATER_INFRASTRUCTURE",
            issued_at=now,
            evidence_commitment=TEST_EVIDENCE_COMMITMENT,
        )
        sig = sign_receipt(rec, VENDOR_WELL_DRILL.private_key, domain)

        claim_res = db.process_and_persist_claim(
            receipt=rec,
            signature=sig,
            claim_amount=500000,
            report_id="REPORT-DEMO-01",
            domain=domain,
            now=now,
            file_bytes=TEST_EVIDENCE_BYTES,
            salt=TEST_EVIDENCE_SALT,
        )

        is_frozen, freeze_reason = db.is_project_frozen("WATER-001")
        release_eval = escrow.evaluate_release("WATER-001")

        return {
            "scenario": "valid_claim",
            "title": "Valid Vendor Claim (Evidence Verified)",
            "status": claim_res["status"],
            "reason": claim_res.get("reason"),
            "explanation": claim_res["explanation"],
            "project_status": "FROZEN" if is_frozen else "ACTIVE",
            "next_release_outcome": "ALLOWED" if release_eval["disbursement_allowed"] else "BLOCKED",
            "next_release_reason": release_eval.get("reason"),
            "disbursement_allowed": claim_res["disbursement_allowed"],
            "checks": claim_res["checks"],
            "details": {
                "claim_id": claim_res.get("claim_id"),
                "claimed_amount": claim_res.get("claimed_amount"),
                "remaining_balance": claim_res.get("remaining_balance"),
            },
        }

    elif name == "valid_claim_evidence_omitted":
        rec = Receipt(
            project_id="WATER-001",
            vendor_id=VENDOR_WELL_DRILL.vendor_id,
            invoice_id="INV-DEMO-OMIT-001",
            invoice_total=500000,  # $5,000 USD
            currency="USD",
            category="WATER_INFRASTRUCTURE",
            issued_at=now,
            evidence_commitment="0x" + "aa" * 32,
        )
        sig = sign_receipt(rec, VENDOR_WELL_DRILL.private_key, domain)

        claim_res = db.process_and_persist_claim(
            receipt=rec,
            signature=sig,
            claim_amount=500000,
            report_id="REPORT-DEMO-OMIT-01",
            domain=domain,
            now=now,
            file_bytes=None,
            salt=None,
        )

        is_frozen, freeze_reason = db.is_project_frozen("WATER-001")
        release_eval = escrow.evaluate_release("WATER-001")

        return {
            "scenario": "valid_claim_evidence_omitted",
            "title": "Valid Vendor Claim (Evidence Omitted)",
            "status": claim_res["status"],
            "reason": claim_res.get("reason"),
            "explanation": claim_res["explanation"],
            "project_status": "FROZEN" if is_frozen else "ACTIVE",
            "next_release_outcome": "ALLOWED" if release_eval["disbursement_allowed"] else "BLOCKED",
            "next_release_reason": release_eval.get("reason"),
            "disbursement_allowed": claim_res["disbursement_allowed"],
            "checks": claim_res["checks"],
            "details": {
                "claim_id": claim_res.get("claim_id"),
                "claimed_amount": claim_res.get("claimed_amount"),
                "remaining_balance": claim_res.get("remaining_balance"),
            },
        }

    elif name == "tampered_amount":
        # 1. Genuine receipt for $5,000 signed by vendor
        honest_rec = Receipt(
            project_id="WATER-001",
            vendor_id=VENDOR_WELL_DRILL.vendor_id,
            invoice_id="INV-TAMPER-002",
            invoice_total=500000,  # $5,000 USD
            currency="USD",
            category="WATER_INFRASTRUCTURE",
            issued_at=now,
            evidence_commitment="0x" + "bb" * 32,
        )
        original_sig = sign_receipt(honest_rec, VENDOR_WELL_DRILL.private_key, domain)

        # 2. Tampered claim altering invoice_total to $50,000
        tampered_rec = Receipt(
            project_id="WATER-001",
            vendor_id=VENDOR_WELL_DRILL.vendor_id,
            invoice_id="INV-TAMPER-002",
            invoice_total=5000000,  # Tampered: $50,000 USD!
            currency="USD",
            category="WATER_INFRASTRUCTURE",
            issued_at=now,
            evidence_commitment="0x" + "bb" * 32,
        )

        claim_res = db.process_and_persist_claim(
            receipt=tampered_rec,
            signature=original_sig,
            claim_amount=5000000,
            report_id="REPORT-TAMPER",
            domain=domain,
            now=now,
        )

        is_frozen, freeze_reason = db.is_project_frozen("WATER-001")
        release_eval = escrow.evaluate_release("WATER-001")

        return {
            "scenario": "tampered_amount",
            "title": "Tampered Invoice Amount",
            "status": claim_res["status"],
            "reason": claim_res.get("reason"),
            "explanation": claim_res["explanation"],
            "project_status": "FROZEN" if is_frozen else "ACTIVE",
            "next_release_outcome": "ALLOWED" if release_eval["disbursement_allowed"] else "BLOCKED",
            "next_release_reason": release_eval.get("reason"),
            "disbursement_allowed": claim_res["disbursement_allowed"],
            "checks": claim_res["checks"],
            "details": {
                "freeze_reason": freeze_reason,
            },
        }

    elif name == "forged_signature":
        rec = Receipt(
            project_id="WATER-001",
            vendor_id=VENDOR_WELL_DRILL.vendor_id,
            invoice_id="INV-FORGE-003",
            invoice_total=400000,  # $4,000 USD
            currency="USD",
            category="WATER_INFRASTRUCTURE",
            issued_at=now,
            evidence_commitment="0x" + "cc" * 32,
        )
        forged_sig = sign_receipt(rec, ATTACKER_SIGNER.private_key, domain)

        claim_res = db.process_and_persist_claim(
            receipt=rec,
            signature=forged_sig,
            claim_amount=400000,
            report_id="REPORT-FORGE",
            domain=domain,
            now=now,
        )

        is_frozen, freeze_reason = db.is_project_frozen("WATER-001")
        release_eval = escrow.evaluate_release("WATER-001")

        return {
            "scenario": "forged_signature",
            "title": "Forged Vendor Signature",
            "status": claim_res["status"],
            "reason": claim_res.get("reason"),
            "explanation": claim_res["explanation"],
            "project_status": "FROZEN" if is_frozen else "ACTIVE",
            "next_release_outcome": "ALLOWED" if release_eval["disbursement_allowed"] else "BLOCKED",
            "next_release_reason": release_eval.get("reason"),
            "disbursement_allowed": claim_res["disbursement_allowed"],
            "checks": claim_res["checks"],
            "details": {
                "freeze_reason": freeze_reason,
            },
        }

    elif name == "unregistered_vendor":
        rec = Receipt(
            project_id="WATER-001",
            vendor_id=VENDOR_UNREGISTERED.vendor_id,
            invoice_id="INV-UNREG-004",
            invoice_total=300000,
            currency="USD",
            category="WATER_INFRASTRUCTURE",
            issued_at=now,
            evidence_commitment="0x" + "dd" * 32,
        )
        sig = sign_receipt(rec, VENDOR_UNREGISTERED.private_key, domain)

        claim_res = db.process_and_persist_claim(
            receipt=rec,
            signature=sig,
            claim_amount=300000,
            report_id="REPORT-UNREG",
            domain=domain,
            now=now,
        )

        is_frozen, freeze_reason = db.is_project_frozen("WATER-001")
        release_eval = escrow.evaluate_release("WATER-001")

        return {
            "scenario": "unregistered_vendor",
            "title": "Unregistered Vendor Claim",
            "status": claim_res["status"],
            "reason": claim_res.get("reason"),
            "explanation": claim_res["explanation"],
            "project_status": "FROZEN" if is_frozen else "ACTIVE",
            "next_release_outcome": "ALLOWED" if release_eval["disbursement_allowed"] else "BLOCKED",
            "next_release_reason": release_eval.get("reason"),
            "disbursement_allowed": claim_res["disbursement_allowed"],
            "checks": claim_res["checks"],
            "details": {
                "vendor_id": VENDOR_UNREGISTERED.vendor_id,
            },
        }

    elif name == "duplicate_report":
        # First: Legitimate claim under REPORT-A
        rec = Receipt(
            project_id="WATER-001",
            vendor_id=VENDOR_WELL_DRILL.vendor_id,
            invoice_id="INV-CROSS-REPORT-005",
            invoice_total=450000,  # $4,500 USD
            currency="USD",
            category="WATER_INFRASTRUCTURE",
            issued_at=now,
            evidence_commitment="0x" + "ee" * 32,
        )
        sig = sign_receipt(rec, VENDOR_WELL_DRILL.private_key, domain)

        first_claim = db.process_and_persist_claim(
            receipt=rec,
            signature=sig,
            claim_amount=450000,
            report_id="REPORT-ORIGINAL-A",
            domain=domain,
            now=now,
        )
        assert first_claim["status"] == "VERIFIED"

        # Second: Double claim under REPORT-B
        duplicate_claim = db.process_and_persist_claim(
            receipt=rec,
            signature=sig,
            claim_amount=450000,
            report_id="REPORT-DUPLICATE-B",
            domain=domain,
            now=now,
        )

        is_frozen, freeze_reason = db.is_project_frozen("WATER-001")
        release_eval = escrow.evaluate_release("WATER-001")

        return {
            "scenario": "duplicate_report",
            "title": "Cross-Report Double Count (Duplicate Invoice)",
            "status": duplicate_claim["status"],
            "reason": duplicate_claim.get("reason"),
            "explanation": duplicate_claim["explanation"],
            "project_status": "FROZEN" if is_frozen else "ACTIVE",
            "next_release_outcome": "ALLOWED" if release_eval["disbursement_allowed"] else "BLOCKED",
            "next_release_reason": release_eval.get("reason"),
            "disbursement_allowed": duplicate_claim["disbursement_allowed"],
            "checks": duplicate_claim["checks"],
            "details": {
                "original_report_id": "REPORT-ORIGINAL-A",
                "attempted_report_id": "REPORT-DUPLICATE-B",
                "freeze_reason": freeze_reason,
            },
        }

    elif name == "out_of_purpose":
        # Receipt claiming unapproved category (e.g. POLITICAL_CAMPAIGN)
        # We manually construct a Receipt dict because Receipt model normalizes category
        # against ALLOWED_CATEGORIES, but here we test what happens when an off-purpose
        # category (like LUXURY_GOODS or EMERGENCY_RELIEF which is valid in general, but not
        # for a WATER_INFRASTRUCTURE project) is claimed!
        # Note: In ALLOWED_CATEGORIES: EMERGENCY_RELIEF, MEDICAL_SUPPLIES, FOOD_SUPPLIES,
        # EDUCATION, INFRASTRUCTURE, WATER_INFRASTRUCTURE, LOGISTICS, ADMINISTRATIVE.
        # Project WATER-001 purpose is "WATER_INFRASTRUCTURE".
        # If the claim specifies "FOOD_SUPPLIES" or "ADMINISTRATIVE", it is valid receipt syntax,
        # but rejected by project purpose policy!
        rec = Receipt(
            project_id="WATER-001",
            vendor_id=VENDOR_WELL_DRILL.vendor_id,
            invoice_id="INV-PURPOSE-006",
            invoice_total=350000,
            currency="USD",
            category="FOOD_SUPPLIES",  # Diverted from WATER_INFRASTRUCTURE!
            issued_at=now,
            evidence_commitment="0x" + "ff" * 32,
        )
        sig = sign_receipt(rec, VENDOR_WELL_DRILL.private_key, domain)

        claim_res = db.process_and_persist_claim(
            receipt=rec,
            signature=sig,
            claim_amount=350000,
            report_id="REPORT-PURPOSE",
            domain=domain,
            now=now,
        )

        is_frozen, freeze_reason = db.is_project_frozen("WATER-001")
        release_eval = escrow.evaluate_release("WATER-001")

        return {
            "scenario": "out_of_purpose",
            "title": "Out-of-Purpose Fund Diversion",
            "status": claim_res["status"],
            "reason": claim_res.get("reason"),
            "explanation": claim_res["explanation"],
            "project_status": "FROZEN" if is_frozen else "ACTIVE",
            "next_release_outcome": "ALLOWED" if release_eval["disbursement_allowed"] else "BLOCKED",
            "next_release_reason": release_eval.get("reason"),
            "disbursement_allowed": claim_res["disbursement_allowed"],
            "checks": claim_res["checks"],
            "details": {
                "project_purpose": "WATER_INFRASTRUCTURE",
                "claimed_category": "FOOD_SUPPLIES",
                "freeze_reason": freeze_reason,
            },
        }

    else:
        raise ValueError(f"Unknown scenario name: {name!r}")
